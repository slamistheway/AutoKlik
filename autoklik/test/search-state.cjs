const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const context = {exports: {}, URLSearchParams};
const source = fs.readFileSync(path.join(__dirname, '../src/shared/search-state.ts'), 'utf8');
vm.runInNewContext(ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText, context);
const {searchParams, searchChips, removeSearchFilter, filterKeys} = context.exports;
const draft = Object.fromEntries(Array.from(filterKeys, key => [key, key.endsWith('Min') ? '0' : 'value']));
const params = searchParams({...draft, page: '3', sort: 'priceAsc', userId: '999'}, true);
for (const key of filterKeys) assert.ok(params.has(key), `${key} is sent to the API`);
assert.equal(params.get('priceMin'), '0');
assert.equal(params.has('userId'), false);
assert.equal(searchParams(Object.fromEntries(params)).has('page'), false, 'saved searches omit pagination and sorting');
assert.equal(searchParams(Object.fromEntries(params)).has('sort'), false);
const original = new URLSearchParams('brands=VW,Audi&models=Golf&priceMax=15000&fuel=diesel&page=4&sort=priceAsc');
const removed = removeSearchFilter(original, 'brands', 'VW');
assert.equal(removed.get('brands'), 'Audi');
assert.equal(removed.has('models'), false, 'brand changes invalidate model selection');
assert.equal(removed.has('page'), false, 'chip changes reset pagination');
assert.equal(removed.get('priceMax'), '15000');
assert.equal(removed.get('sort'), 'priceAsc');
assert.equal(original.get('page'), '4', 'chip removal does not mutate its input');
const chips = searchChips(original);
assert.ok(chips.some(chip => chip.label === 'Cijena (€) do: 15000'));
assert.ok(chips.some(chip => chip.label === 'Gorivo: Dizel'));
assert.equal(chips.filter(chip => chip.key === 'brands').length, 2);
console.log('PASS: every filter serializes, zero ranges survive, chips remove individual values/dependencies, pagination resets, sort is preserved and saved searches exclude paging.');
